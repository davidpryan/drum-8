"""The kit's tables of Hortator's drum models (app/dsp/hort_models.inc), read from the models' own rows of Hortator's
DMODELS (each file's DM_*_DEF in app/dsp/hort/: the name, the eight SOUND knobs with their ranges and defaults, the
trigger and the render). In Hortator's order, less SAMPL and ACID (tools/import_hortator.sh).
  tools/gen_hort_models.py [OUT]         (the result is committed)
A knob on the kit is 0..127 whatever the model's range: TUNE (-24..24) is the knob about 64, a list (FM's RATIO) the
knob's sixteenths; hort.c hort_start maps them by HORT_RANGES. TRIM: each model's gain on Hortator's full scale, set
so its defaults peak where the kit's models do (kicks and snares -6 dBFS, hats and cymbals -12, the rest -9;
tests/host/drumline_test.c measures them)."""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "app" / "dsp" / "hort"
ORDER = ["K808", "K909", "S808", "S909", "C808", "C909", "HATC", "HATO", "CYMB", "COWB", "TOM", "CONGA", "RIM", "CLAVE",
         "KBOOM", "KPUNC", "SSNAP", "SCRAK", "HMETL", "HNOIS", "MEMB", "FM", "KTRX", "SDTRX", "XTTRX", "XCTRX", "CPTRX",
         "RSTRX", "CBTRX", "CHTRX", "OHTRX", "CYTRX", "MATRX", "CLTRX", "B2TRX", "BDEFM", "SDEFM", "XTEFM", "CPEFM",
         "RSEFM", "CBEFM", "HHEFM", "CYEFM"]
KIT_NAME = {"TOM": "c tom", "CONGA": "c conga", "FM": "fm perc"}        # (the kit has a tom, a conga and an fm)
PAD = {"TOM": "ctom", "CONGA": "ccong", "FM": "fmprc"}
PAD4 = {"TOM": "ctom", "CONGA": "ccga", "FM": "fmpc", "PUNCH": "pnch", "CRACK": "crck", "METAL": "metl", "CLAVE": "clav"}
LISTS = {"N_FMRATIO": 16}                                               # a PE knob's list: its length
# level groups: the peak of the defaults, dBFS
KICKS = {"K808", "K909", "BOOM", "PUNCH", "BDTRX", "B2TRX", "BDEFM", "S808", "S909", "SNAP", "CRACK", "SDTRX", "SDEFM"}
METALS = {"HATC", "HATO", "CYMB", "METAL", "HISS", "CHTRX", "OHTRX", "CYTRX", "HHEFM", "CYEFM"}
# measured: each model's peak at its defaults with trim 1 (tools/gen_hort_models.py --peaks prints the kit's own)
PEAK_DB = {"K808": -6.7, "K909": -6.8, "S808": -4.3, "S909": -7.6, "C808": -13.0, "C909": -12.4, "HATC": -21.9, "HATO":
           -27.5, "CYMB": -18.1, "COWB": -8.7, "TOM": -6.4, "CONGA": -5.2, "RIM": -4.6, "CLAVE": -5.5, "BOOM": -10.9,
           "PUNCH": -8.3, "SNAP": -7.2, "CRACK": -7.6, "METAL": -10.7, "HISS": -9.5, "SKIN": -4.1, "FM": -2.3, "BDTRX":
           -2.7, "SDTRX": -11.2, "TMTRX": -15.3, "CGTRX": -13.4, "CPTRX": -12.4, "RSTRX": -13.9, "CBTRX": -14.6,
           "CHTRX": -28.5, "OHTRX": -28.3, "CYTRX": -18.7, "SHTRX": -30.3, "CLTRX": -14.8, "B2TRX": -3.9, "BDEFM":
           -6.7, "SDEFM": -31.8, "TMEFM": 2.7, "CPEFM": -21.5, "RSEFM": -17.8, "CBEFM": -10.0, "HHEFM": -25.5, "CYEFM":
           -21.1}


def target_db(name):
    if name == "SDEFM":                     # (its defaults are its quiet end: TUNE up or HPF down is 13 dB louder)
        return -15.0
    return -6.0 if name in KICKS else -12.0 if name in METALS else -9.0


def rows():
    text = "".join((SRC / f.name).read_text() for f in sorted(SRC.glob("dm_*.c")))
    text = text.replace("\\\n", " ")
    out = []
    for key in ORDER:
        m = re.search(r"#define DM_%s_DEF \{(.*)\}\s*$" % key, text, re.M)
        assert m, key
        body = m.group(1)
        name = re.match(r'\s*"(\w+)"', body).group(1)
        knobs = []
        for k in re.finditer(r'P([DE])\("([^"]+)",\s*(\w+),\s*(-?\d+)(?:,\s*(-?\d+),\s*(-?\d+))?\)', body):
            if k.group(1) == "D":
                lo, hi, df = int(k.group(4)), int(k.group(5)), int(k.group(6))
            else:
                lo, hi, df = 0, LISTS[k.group(3)] - 1, int(k.group(4))
            knobs.append((k.group(2).lower(), lo, hi, df))
        assert len(knobs) == 8, (key, knobs)
        tail = body[body.rindex("}") + 1:].split(",")
        trig, rend = tail[1].strip(), tail[2].strip()
        n = max(i + 1 for i, k in enumerate(knobs) if k[0] != "-")
        assert all(k[0] != "-" for k in knobs[:n]), key
        out.append(dict(key=key, name=name, knobs=knobs, n=n, trig=trig, rend=rend))
    return out


def kit_value(lo, hi, df):
    if lo < 0:
        return df + 64
    if hi == 127 or hi == 0:                                # (0: a knob the model has not)
        return df
    return ((2 * df + 1) * 64) // (hi + 1)                  # a list: the middle of the entry's stretch of the knob


def main(path):
    R = rows()
    q = lambda s: '"%s"' % s
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* generated by tools/gen_hort_models.py from Hortator's DM_*_DEF rows (app/dsp/hort/): do not edit */",
         "/* X(id, the kit's name, the pad's name, its four letters, trigger, render, knobs) */",
         "#define HORT_MODELS(X) \\"]
    for r in R:
        nm = KIT_NAME.get(r["name"], r["name"].lower())
        pad = PAD.get(r["name"], r["name"].lower())
        p4 = PAD4.get(r["name"])
        if not p4:
            p4 = pad[:2] + ("tx" if pad.endswith("trx") else "fm") if pad.endswith(("trx", "efm")) else pad[:4]
        assert len(pad) <= 5 and len(p4) <= 4
        L.append(f"    X({r['name']}, {q(nm)}, {q(pad)}, {q(p4)}, {r['trig']}, {r['rend']}, {r['n']}) \\")
    L.append("")

    def table(name, f):
        L.append(f"#define {name} \\")
        for r in R:
            L.append("    {" + ", ".join(f(r)) + "}, \\")
        L.append("")
    table("HORT_KNOBS", lambda r: [q(k[0]) for k in r["knobs"][:min(4, r["n"])]])
    table("HORT_KNOBS2", lambda r: [q(k[0]) for k in r["knobs"][4:r["n"]]] or ["0"])
    table("HORT_DEFAULTS", lambda r: [str(kit_value(*k[1:])) for k in r["knobs"][:4]])
    table("HORT_DEFAULTS2", lambda r: [str(kit_value(*k[1:])) for k in r["knobs"][4:]])
    table("HORT_RANGES", lambda r: ["{%d, %d}" % (k[1], k[2]) for k in r["knobs"]])
    L.append("/* drumline.c SPEC: the length's range (unused: the models' own), the trim */")
    L.append("#define HORT_SPECS \\")
    for r in R:
        t = 10 ** ((target_db(r["name"]) - PEAK_DB.get(r["name"], target_db(r["name"]))) / 20)
        L.append(f"    {{0.1f, 4.0f, {t:.3f}f}}, /* {r['name']} */ \\")
    L.append("")
    Path(path).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(HERE.parent / "app" / "dsp" / "hort_models.inc"))
