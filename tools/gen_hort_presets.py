"""Hortator's factory presets as the kit's drum sounds (app/dsp/hort_presets.inc), from tools/hort_presets.json
(Hortator's tools/presets.json, brought in by tools/import_hortator.sh): each a model and its eight SOUND knobs. In
Hortator's order (its banks MACHINEDRUM, MODERN, CLASSIC), less the presets of the models the kit has not (SAMPL, ACID).
The knobs are written as the kit holds them, 0..127 (tools/gen_hort_models.py kit_value).
  tools/gen_hort_presets.py [OUT]        (the result is committed)"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_hort_models as gm  # noqa: E402

BANKS = ["MACHINEDRUM", "MODERN", "CLASSIC"]


def presets():
    """[(name, the model's index (hort.h HM_*), its eight knobs on the kit)]"""
    rows = gm.rows()
    idx = {r["key"]: i for i, r in enumerate(rows)}
    banks = {b["bank"]: b["presets"] for b in json.loads((HERE / "hort_presets.json").read_text())}
    out = []
    for b in BANKS:
        for p in banks[b]:
            if p["model"] not in idx:
                continue
            r = rows[idx[p["model"]]]
            kn = []
            for (name, lo, hi, df), v in zip(r["knobs"], p["k"]):
                assert name == "-" or lo <= v <= hi, (p["name"], name, v)
                kn.append(gm.kit_value(lo, hi, v))
            assert len(p["name"]) <= 8
            out.append((p["name"], idx[p["model"]], kn))
    assert len({n for n, _, _ in out}) == len(out) < 256
    return out


def main(path):
    P = presets()
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* generated by tools/gen_hort_presets.py from Hortator's factory presets (tools/hort_presets.json): do not edit */",
         f"#define NHPRESET {len(P)}",
         "/* the model (hort.h HM_*), its eight knobs as the kit holds them, the name */",
         "static const struct { uint8_t model, k[8]; char name[9]; } HPRESET[NHPRESET] = {"]
    for name, m, kn in P:
        L.append("    {%d, {%s}, \"%s\"}," % (m, ", ".join(map(str, kn)), name))
    L.append("};")
    Path(path).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(HERE.parent / "app" / "dsp" / "hort_presets.inc"))
