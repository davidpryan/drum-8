"""Hortator's factory presets as the kit's drum sounds (app/dsp/hort_presets.inc), from tools/hort_presets.json
(Hortator's tools/presets.json, brought in by tools/import_hortator.sh): each a model and its eight SOUND knobs. In
Hortator's order (its banks MACHINEDRUM, MODERN, CLASSIC), less the presets of the models the kit has not (SAMPL, ACID).
The knobs are written as the kit holds them, 0..127 (tools/gen_hort_models.py kit_value).
  tools/gen_hort_presets.py [OUT]        (the result is committed)"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_hort_models as gm  # noqa: E402

BANKS = ["MACHINEDRUM", "MODERN", "CLASSIC"]
# DRUM SOUND's types (app/pages.c HPT_*): the presets are listed by type, in the banks' order within one
TYPES = ["kick", "snare", "hat", "clap", "tom", "perc", "cymbal"]
TYPE_OF = {"kick": "K808 K909 KBOOM KPUNC KTRX B2TRX BDEFM", "snare": "S808 S909 SSNAP SCRAK SDTRX SDEFM",
           "hat": "HATC HATO HMETL HNOIS CHTRX OHTRX HHEFM", "clap": "C808 C909 CPTRX CPEFM",
           "tom": "TOM XTTRX XTEFM MEMB", "perc": "CONGA RIM CLAVE COWB FM XCTRX RSTRX CBTRX MATRX CLTRX RSEFM CBEFM",
           "cymbal": "CYMB CYTRX CYEFM"}
MODEL_TYPE = {m: TYPES.index(ty) for ty, ms in TYPE_OF.items() for m in ms.split()}


def presets():
    """[(name, the model's index (hort.h HM_*), its eight knobs on the kit)] by type, and each type's first"""
    rows = gm.rows()
    idx = {r["key"]: i for i, r in enumerate(rows)}
    banks = {b["bank"]: b["presets"] for b in json.loads((HERE / "hort_presets.json").read_text())}
    out = []
    for b in BANKS:
        for p in banks[b]:
            if p["model"] not in idx:
                continue
            r = rows[idx[p["model"]]]
            kn = []
            for (name, lo, hi, df), v in zip(r["knobs"], p["k"]):
                assert name == "-" or lo <= v <= hi, (p["name"], name, v)
                kn.append(gm.kit_value(lo, hi, v))
            assert len(p["name"]) <= 8
            out.append((p["name"], idx[p["model"]], kn, MODEL_TYPE[p["model"]]))
    assert len({n for n, _, _, _ in out}) == len(out) < 256
    out.sort(key=lambda p: p[3])                            # (stable: the banks' order within a type)
    return [p[:3] for p in out], [sum(1 for p in out if p[3] < ty) for ty in range(len(TYPES) + 1)]


def main(path):
    P, starts = presets()
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* generated by tools/gen_hort_presets.py from Hortator's factory presets (tools/hort_presets.json): do not edit */",
         f"#define NHPRESET {len(P)}",
         "/* the model (hort.h HM_*), its eight knobs as the kit holds them, the name */",
         "static const struct { uint8_t model, k[8]; char name[9]; } HPRESET[NHPRESET] = {"]
    for name, m, kn in P:
        L.append("    {%d, {%s}, \"%s\"}," % (m, ", ".join(map(str, kn)), name))
    L.append("};")
    L.append(f"#define NHPT {len(TYPES)}")
    L.append("static const char *const HPT_NAME[NHPT] = {" + ", ".join(f'"{n}"' for n in TYPES) + "};")
    L.append("static const uint8_t HPT_START[NHPT + 1] = {" + ", ".join(map(str, starts)) + "};   /* a type's first; its end */")
    Path(path).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(HERE.parent / "app" / "dsp" / "hort_presets.inc"))
